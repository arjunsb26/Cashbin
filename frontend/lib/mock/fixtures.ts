function identification(
  method: Identification["method"],
  label: string,
  itemClass: Identification["item_class"],
  confidence: number,
  candidates: { label: string; p: number }[],
  posterior: { label: string; p: number }[] | null,
  cost: number,
): Identification {
  return {
    method,
    label,
    item_class: itemClass,
    confidence,
    candidates,
    posterior,
    used_mass_prior: posterior !== null,
    latency_ms: method === "cloud" ? 1420 : 180,
    cost_microusd: cost,
    is_final: true,
    visible_text: null,
  };
}

