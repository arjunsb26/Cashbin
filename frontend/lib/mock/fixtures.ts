function trace(baseline: number, step: number, seed: number): WeightTrace {
  const points = [];
  for (let i = 0; i < 90; i += 1) {
    const t = i * 100;
    const noise = Math.sin((i + seed) * 1.7) * 0.6 + Math.cos((i + seed) * 0.6) * 0.4;
    let g = baseline + noise;
    if (i >= 30 && i < 34) g = baseline + step * 1.35 + noise * 3;
    else if (i >= 34) g = baseline + step + noise;
    points.push({ t_ms: t, g: Number(g.toFixed(2)) });
  }
  return { points, open_t_ms: 3000, settle_t_ms: 4400, baseline_g: baseline };
}

